/**
 * Copies the SQL migrations into one TypeScript module, in order.
 *
 * The server applies migrations itself when it starts (server/db/migrate.ts). A serverless function has no
 * folder of .sql files beside it, so the SQL travels inside the code. `npm run db:generate` runs this; a test
 * fails if the module and the .sql files ever disagree.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const dir = fileURLToPath(new URL('../server/db/migrations/', import.meta.url));
const out = fileURLToPath(new URL('../server/db/migrations.generated.ts', import.meta.url));

interface Journal {
  entries: { idx: number; tag: string }[];
}

export function renderMigrationsModule(): string {
  const journal = JSON.parse(readFileSync(`${dir}meta/_journal.json`, 'utf8')) as Journal;
  const entries = [...journal.entries].sort((a, b) => a.idx - b.idx);
  const lines = [
    '// GENERATED by scripts/embed-migrations.ts from server/db/migrations/*.sql — do not edit.',
    '',
    'export interface EmbeddedMigration {',
    '  tag: string;',
    '  sql: string;',
    '}',
    '',
    'export const MIGRATIONS: readonly EmbeddedMigration[] = [',
  ];
  for (const entry of entries) {
    const sql = readFileSync(`${dir}${entry.tag}.sql`, 'utf8');
    lines.push(`  { tag: ${JSON.stringify(entry.tag)}, sql: ${JSON.stringify(sql)} },`);
  }
  lines.push('];', '');
  return lines.join('\n');
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  writeFileSync(out, renderMigrationsModule());
  console.log(`Wrote ${out}`);
}
